import json, gzip, hashlib, os
from questions import Q, DUCK_ONLY
REPO = '/home/claude/astrabi-analytics'
outdir = f'{REPO}/public/benchmarks/business-v1/datasets'; os.makedirs(outdir, exist_ok=True)
expected = json.load(open('expected.json'))
refs = {}
for key in ['retail', 'weekly', 'appointments', 'employees']:
    raw = open(f'ds_{key}.json', 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    name = f'{key}-{sha[:12]}.json.gz'
    with gzip.GzipFile(f'{outdir}/{name}', 'wb', mtime=0) as f: f.write(raw)
    refs[key] = (f'/benchmarks/business-v1/datasets/{name}', sha)
cases = []
for qid, key, diff, cat, question, sql in Q:
    cases.append({
        'id': f'business-{qid}', 'suiteId': 'quickinsight-business', 'sourceId': f'quickinsight-business:{key}:{qid}',
        'question': question, 'context': None, 'category': cat, 'difficulty': diff,
        'datasetRef': refs[key][0], 'datasetSha256': refs[key][1],
        'goldSql': sql if sql else DUCK_ONLY[qid], 'expectedRows': expected[qid],
        'comparison': {'orderMatters': False, 'absoluteTolerance': 0.01, 'relativeTolerance': 0.005},
        'tags': ['business', key], 'oracleQuality': 'no_issue_found',
    })
manifest = hashlib.sha256(json.dumps(cases, sort_keys=True).encode()).hexdigest()
ts = f"""// Generated by scripts/build-business-benchmark (scratch tooling). Never edit case content manually.
// Questions a business user types, on four cleaned datasets (retail orders, weekly store
// sales, appointments, employees). Gold SQL was frozen with SQLite and is re-run on DuckDB
// before every case, so a wrong gold answer shows up as a fixture error, never as a score.
import type {{ BenchmarkCase, BenchmarkSuite }} from './types';
const CASES: BenchmarkCase[] = {json.dumps(cases, indent=2, ensure_ascii=False)};

export const BUSINESS_BENCHMARK_SUITE: BenchmarkSuite = {{
  id: 'quickinsight-business',
  name: 'QuickInsight business questions',
  shortName: 'Business',
  version: '1.0.0',
  manifestSha256: '{manifest}',
  description: '{len(cases)} plain-English business questions on retail orders, weekly store sales, appointments and HR data.',
  methodology: 'Execution accuracy: the SQL the AI writes is run on the full cleaned dataset and its result compared with a frozen gold answer (order-insensitive, 0.5% / 0.01 tolerance).',
  accent: 'amber',
  evaluationClass: 'curated-compatibility',
  attribution: {{ benchmark: 'QuickInsight business benchmark', homepage: 'https://github.com/Saicharan-saich/astrabi-analytics', license: 'Synthetic data', notice: 'Generated data; no real customers, patients or employees.' }},
  cases: CASES,
}};
"""
open(f'{REPO}/services/benchmark/businessFixtures.generated.ts', 'w').write(ts)
print(len(cases), manifest[:12], refs)
