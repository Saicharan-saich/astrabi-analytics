"""Write the datasets (gzipped, named by checksum) and services/benchmark/ownerFixtures.generated.ts."""
import json, gzip, hashlib, os
from questions import Q
REPO = '/home/claude/astrabi-analytics'
outdir = f'{REPO}/public/benchmarks/owner-v1/datasets'
os.makedirs(outdir, exist_ok=True)
for old in os.listdir(outdir):
    os.remove(os.path.join(outdir, old))
expected = json.load(open('expected.json'))
refs = {}
for key in ['cafe', 'shop', 'online']:
    raw = open(f'ds_{key}.json', 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    name = f'{key}-{sha[:12]}.json.gz'
    with gzip.GzipFile(f'{outdir}/{name}', 'wb', mtime=0) as f:
        f.write(raw)
    refs[key] = (f'/benchmarks/owner-v1/datasets/{name}', sha)
NAMES = {'cafe': 'café (Square item sales)', 'shop': 'shop (till export)', 'online': 'online shop (Shopify orders)'}
cases = []
for c in Q:
    seen = [json.dumps(expected[c['id']]['rows'], sort_keys=True)]
    alternatives = []
    for (reading, sql, _ref), rows in zip(c['alts'], expected[c['id']]['alts']):
        key = json.dumps(rows, sort_keys=True)
        if key in seen:
            continue  # the same answer as a reading already accepted
        seen.append(key)
        alternatives.append({'reading': reading, 'goldSql': sql, 'expectedRows': rows})
    case = {
        'id': f"owner-{c['id']}", 'suiteId': 'quickinsight-owner', 'sourceId': f"quickinsight-owner:{c['ds']}:{c['id']}",
        'question': c['question'], 'context': None, 'category': c['category'], 'difficulty': c['difficulty'],
        'datasetRef': refs[c['ds']][0], 'datasetSha256': refs[c['ds']][1],
        'goldSql': c['sql'], 'expectedRows': expected[c['id']]['rows'],
        'comparison': {'orderMatters': False, 'absoluteTolerance': 0.01, 'relativeTolerance': 0.005},
        'tags': ['owner', c['ds']], 'oracleQuality': 'no_issue_found',
    }
    if alternatives:
        case['goldAlternatives'] = alternatives
    cases.append(case)
manifest = hashlib.sha256(json.dumps(cases, sort_keys=True).encode()).hexdigest()
counts = {k: sum(1 for c in Q if c['ds'] == k) for k in NAMES}
ts = f"""// Generated by scripts/owner-benchmark (emit.py). Never edit case content by hand.
// Questions small-business owners type, on three exports as they come out of the till or shop:
// a café's Square item sales, a shop's till export and an online shop's Shopify orders, each
// cleaned by the app's own cleaner. Frozen answers were worked out in pandas; the gold SQL is
// re-run in DuckDB before every case (and in CI), so the two engines must agree.
import type {{ BenchmarkCase, BenchmarkSuite }} from './types';
const CASES: BenchmarkCase[] = {json.dumps(cases, indent=2, ensure_ascii=False)};

export const OWNER_BENCHMARK_SUITE: BenchmarkSuite = {{
  id: 'quickinsight-owner',
  name: 'QuickInsight owner questions',
  shortName: 'Owners',
  version: '1.0.0',
  manifestSha256: '{manifest}',
  description: '{len(cases)} questions owners ask about a café ({counts["cafe"]}), a shop ({counts["shop"]}) and an online shop ({counts["online"]}).',
  methodology: 'Execution accuracy on the full cleaned export: the AI\\'s SQL result is compared with a frozen answer (order-insensitive, 0.5% / 0.01 tolerance). Where an owner could fairly mean more than one thing ("sales" before or after discounts, the top item or the top 10), every reading has its own checked answer and any of them passes.',
  accent: 'amber',
  evaluationClass: 'curated-compatibility',
  attribution: {{ benchmark: 'QuickInsight owner benchmark', homepage: 'https://github.com/Saicharan-saich/astrabi-analytics', license: 'Synthetic data', notice: 'Generated exports; no real customers or businesses.' }},
  cases: CASES,
}};
"""
open(f'{REPO}/services/benchmark/ownerFixtures.generated.ts', 'w').write(ts)
print(len(cases), 'cases;', sum(len(c.get('goldAlternatives', [])) for c in cases), 'alternative readings;', manifest[:12], refs)
